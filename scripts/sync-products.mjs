// Nightly product sync for dellis.store.
// Reads both public storefronts and writes products.js, which the Shop section loads.
// If either store can't be read, or Printify's list looks incomplete, it stops without
// changing anything, so the site keeps the last good list.
//
// Run locally:  node scripts/sync-products.mjs

import { writeFileSync, readFileSync, existsSync } from "node:fs";
import { fetchPrintful, fetchPrintify, printifySitemapIds } from "./stores.mjs";

const OUT = new URL("../products.js", import.meta.url);

async function fetchText(url) {
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const res = await fetch(url, {
        headers: { "user-agent": "Mozilla/5.0 (dellis.store product sync)", "accept": "text/html,application/xml" },
      });
      if (!res.ok) throw new Error(`${res.status} ${res.statusText}`);
      return await res.text();
    } catch (err) {
      if (attempt === 3) throw new Error(`Could not read ${url}: ${err.message}`);
      await new Promise((r) => setTimeout(r, 3000 * attempt));
    }
  }
}

// Leftover duplicates like "Kids Rash Guard copy" are skipped.
const isLeftoverCopy = (p) => /\bcopy(\s*\d+)?$/i.test(p.name);

const [printify, printful, sitemapIds] = await Promise.all([
  fetchPrintify(fetchText),
  fetchPrintful(fetchText),
  printifySitemapIds(fetchText),
]);

if (!printify.length) throw new Error("Printify returned no products; keeping the current list.");
if (!printful.length) throw new Error("Printful returned no products; keeping the current list.");

const found = new Set(printify.map((p) => p.link.split("/").pop()));
const missing = sitemapIds.filter((id) => !found.has(id));
if (missing.length) {
  throw new Error(`Printify lists ${sitemapIds.length} products but only ${found.size} were read ` +
    `(missing ${missing.join(", ")}). Keeping the current list.`);
}

const products = [...printify, ...printful].filter((p) => !isLeftoverCopy(p));
const skipped = [...printify, ...printful].filter(isLeftoverCopy).map((p) => p.name);

const body = JSON.stringify(products, null, 2);
const previous = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
if (previous.includes(body)) {
  console.log(`No changes. ${products.length} products (${printify.length} Printify, ${printful.length - skipped.length} Printful).`);
  process.exit(0);
}

writeFileSync(OUT,
  "// Generated by scripts/sync-products.mjs from the Printify and Printful stores.\n" +
  "// Do not edit by hand: changes here are replaced at the next sync.\n" +
  `// Last updated ${new Date().toISOString()}\n` +
  `window.DELLIS_PRODUCTS = ${body};\n`);

console.log(`Updated products.js: ${products.length} products (${printify.length} Printify, ${printful.length - skipped.length} Printful).`);
if (skipped.length) console.log(`Skipped leftover copies: ${skipped.join("; ")}`);
